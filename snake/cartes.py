"""Cartes du jeu.

Chaque carte est dessinée en ASCII : une chaîne de 40 caractères par ligne du
plateau (30 lignes), ``#`` pour un mur et ``.`` pour une case libre.
Les serpents de départ sont donnés tête en premier, sous la forme (colonne, ligne).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import FrozenSet, Sequence, Tuple

from .constantes import LARGEUR_PLATEAU, HAUTEUR_PLATEAU, LIGNES_ENTETE, Case

@dataclass(frozen=True)
class Carte:
    nom: str
    murs: FrozenSet[Case]
    serpents: Tuple[Tuple[Case, ...], ...]

def lire_carte(nom: str, dessin: Sequence[str], serpents) -> Carte:
    """Construit une carte à partir de son dessin ASCII."""
    if len(dessin) != HAUTEUR_PLATEAU or any(len(ligne) != LARGEUR_PLATEAU for ligne in dessin):
        raise ValueError(f"La carte {nom!r} doit faire {LARGEUR_PLATEAU}x{HAUTEUR_PLATEAU} caractères")
    murs = frozenset(
        (colonne, ligne + LIGNES_ENTETE)
        for ligne, rangee in enumerate(dessin)
        for colonne, caractere in enumerate(rangee)
        if caractere == "#"
    )
    return Carte(nom, murs, tuple(tuple(serpent) for serpent in serpents))

